<script setup>
import { ref } from 'vue';

const fileInput = ref(null);
const originalImage = ref(null);
const outputImage = ref(null);
const previewContainer = ref(false);

function previewOriginal() {
  const file = fileInput.value?.files[0];
  if (!file) return;

  if (!originalImage.value) {
    originalImage.value = URL.createObjectURL(file);
  }
  previewContainer.value = true;
}

async function uploadImage() {
  const file = fileInput.value?.files[0];
  if (!file) {
    alert('Selecciona una imagen primero');
    return;
  }

  const formData = new FormData();
  formData.append('file', file);

  try {
    // const apiURL = import.meta.env.VITE_CP_API_GATEWAY_URL;
    const apiURL = window.__ENV__.VITE_CP_API_GATEWAY_URL;
    const response = await fetch(`${apiURL}/upload`, {
      method: 'POST',
      body: formData,
    });

    if (!response.ok) {
      console.error(`Error: ${response.statusText}`);
      alert('Error al procesar la imagen. Intenta nuevamente.');
      return;
    }

    const blob = await response.blob();
    outputImage.value = URL.createObjectURL(blob);
    previewContainer.value = true;
  } catch (error) {
    console.error('Error al subir la imagen:', error);
    alert('Error al procesar la imagen. Intenta nuevamente.');
  }
}
</script>

